create table sales(product text, year integer, income int);

insert into sales(product, year, income)
values
('alpha', 2020, 100),
('alpha', 2021, 120),
('alpha', 2022, 130),
('alpha', 2023, 140),
('beta', 2020, 10),
('beta', 2021, 20),
('beta', 2022, 40),
('beta', 2023, 80),
('gamma', 2020, 80),
('gamma', 2021, 75),
('gamma', 2022, 78),
('gamma', 2023, 80);


-- RESULT:product,2020,2021,2022,2023
-- RESULT:alpha,100,120,130,140
-- RESULT:beta,10,20,40,80
-- RESULT:gamma,80,75,78,80
select
  product,
  sum(income) filter (where year = 2020) as "2020",
  sum(income) filter (where year = 2021) as "2021",
  sum(income) filter (where year = 2022) as "2022",
  sum(income) filter (where year = 2023) as "2023"
from sales
group by product
order by product;

-- RESULT:product,2020,2021,2022,2023
-- RESULT:alpha,100,120,130,140
-- RESULT:beta,10,20,40,80
-- RESULT:gamma,80,75,78,80
select
  product,
  sum(case when year = 2020 then income end) as "2020",
  sum(case when year = 2021 then income end) as "2021",
  sum(case when year = 2022 then income end) as "2022",
  sum(case when year = 2023 then income end) as "2023"
from sales
group by product
order by product;

